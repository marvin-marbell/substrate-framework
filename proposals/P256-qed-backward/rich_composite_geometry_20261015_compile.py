def save(path,value):
    with open(path,'xb') as f:pickle.dump(value,f,protocol=5)


def compile_body(basis,primitive,checkpoint):
    ops={}
    actions={'scalar':lambda v:primitive.collective(v),'electric':primitive.electric,
        'B':lambda v:primitive.field(v,primitive.field_maps['B']),
        'C':lambda v:primitive.field(v,primitive.field_maps['C'])}
    for i,a in np.ndindex(3,3):
        actions[f'vector_{i}_{a}']=lambda v,i=i,a=a:primitive.collective(v,i+1,a)
    for name,action in actions.items():
        ops[name]=basis.matrix(action)
        print(json.dumps({'stage':'actual_original_body_operator','operator':name,'dimension':len(basis.vectors),'nnz':ops[name].nnz}),flush=True)
    save(checkpoint,ops)
    return ops


def reduce_hamiltonian(ops,coupling,rotor,scalar,p,graph):
    n=coupling['dimension'];eye=sparse.eye(ops['B'].shape[0],format='csr')
    c0=angular.project_product(coupling,ops['electric']-p['plaquette']*ops['B'],sparse.eye(10))
    k=angular.right_angular(rotor);kinetic=sparse.csr_matrix((10,10),dtype=complex)
    for a,b in np.ndindex(3,3):kinetic+=graph['inertia_inverse'][a,b]*(k[a]@k[b])/2
    c0+=angular.project_product(coupling,eye,kinetic)
    for i,a in np.ndindex(3,3):c0+=p['vector_velocity']*angular.project_product(coupling,ops[f'vector_{i}_{a}'],rotor['coordinate'][i][a])
    cphi=p['scalar_coupling']*angular.project_product(coupling,ops['scalar'],sparse.eye(10))
    h=sparse.kron(c0,sparse.eye(len(scalar['grid'])),format='csr')
    h+=sparse.kron(cphi,scalar['phi'],format='csr')
    h+=sparse.kron(sparse.eye(n),scalar['H'],format='csr')
    return h,c0,cphi


def main():
    config=json.loads(Path(sys.argv[1]).read_text());out=sys.argv[2];started=time.time()
    with open(config['basis_snapshot'],'rb') as f:data=pickle.load(f)
    p=data['p'];basis=data['basis'];primitive=primitive_for(data);scalar,rotor=model.field_and_rotor(p)
    multiplets,spin_receipt=angular.spin_multiplets(basis,primitive)
    save(out+'_spin.pkl',{'p':p,'multiplets':multiplets,'spin_receipt':spin_receipt})
    Path(out+'_spin.json').write_text(json.dumps(spin_receipt,indent=2)+'\n')
    ops=compile_body(basis,primitive,out+'_operators.pkl')
    gauss_squared=0.;gauss_max=0.
    for packet in basis.vectors:
        for a in range(8):
            image=primitive.gauss(packet,a);v=float(model.inner(image,image).real)
            gauss_squared+=v;gauss_max=max(gauss_max,v)
    receipt={'kind':'ACTUAL_NEW_OCCUPIED_GRAPH_H_NOETHER_REFERENCE_COMPILER','parameters':p,'basis':basis.receipt(),
        'spin':spin_receipt,'global_colour_Gauss_Frobenius_upper':np.sqrt(gauss_squared),'max_basis_Gauss_norm':np.sqrt(gauss_max),
        'graph':{k:(v.tolist() if isinstance(v,np.ndarray) else v) for k,v in primitive.graph.items()},
        'operator_Hermiticity':{name:float(sparse.linalg.norm(op-op.conj().T)) for name,op in ops.items()},'blocks':{}}
    for j2 in config['twice_J']:
        coupling=angular.coupled(basis,multiplets,j2)
        print(json.dumps({'stage':'actual_Noether_block','twice_J':j2,'dimension':coupling['dimension'],'isometry':coupling['isometry_error']}),flush=True)
        save(out+f'_J{j2}_coupling.pkl',coupling)
        h,c0,cphi=reduce_hamiltonian(ops,coupling,rotor,scalar,p,primitive.graph)
        sparse.save_npz(out+f'_J{j2}_H0.npz',h)
        np.random.seed(1900+j2);start=np.random.normal(size=h.shape[0])+1j*np.random.normal(size=h.shape[0])
        count=min(p['low_eigenstates'],h.shape[0]-2)
        energies,states=eigsh(h,k=count,which='SA',tol=p['eigen_tolerance'],v0=start)
        order=np.argsort(energies);energies=energies[order];states=states[:,order]
        residuals=[float(np.linalg.norm(h@states[:,i]-energies[i]*states[:,i])) for i in range(count)]
        np.savez(out+f'_J{j2}_states.npz',energies=energies,states=states)
        block={'coupled_dimension':coupling['dimension'],'full_phi_dimension':h.shape[0],'coupling_isometry_error':coupling['isometry_error'],
            'H_Hermiticity_error':float(sparse.linalg.norm(h-h.conj().T)),'energies':energies.tolist(),'eigen_residuals':residuals,
            'source_scope':'stationary proper J,M=J block; complete other M generated by same isometry. Not a spin penalty.'}
        receipt['blocks'][str(j2)]=block
        Path(out+'_checkpoint.json').write_text(json.dumps(receipt,indent=2)+'\n')
        print(json.dumps({'stage':'pole_block_complete','twice_J':j2,'energy':float(energies[0]),'maxres':max(residuals)}),flush=True)
    receipt['resource']={'peak_RSS_KiB':resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,'elapsed_seconds':time.time()-started}
    Path(out+'_result.json').write_text(json.dumps(receipt,indent=2)+'\n')
    print(json.dumps(receipt['resource']),flush=True)


if __name__=='__main__':main()
