"""Independent exact adverse controls; no target import or ground computation."""
from __future__ import annotations

import argparse
from fractions import Fraction as F
import hashlib
import json
from pathlib import Path
from typing import Any


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def arc_constants(ell: int) -> dict[str, Any]:
    root_k = 2 ** 4100
    m = 2 ** ell
    a = F(1, root_k * m * m)
    delta = a / 2
    s = delta / m
    r = 1 - s
    probability = F(1, m) + root_k * a * (m - 1)
    # Sum the individual rotation losses, rather than reuse a producer formula.
    losses = 2 * root_k * a * F(m * (m - 1), 2)
    assert probability == (1 + losses) / m
    assert probability == F(2, m) - F(1, m * m)
    error = 64 * (s / delta) ** 2 + 16 * probability
    assert error == F(32, m) + F(48, m * m)
    assert error < F(128, m)
    assert m * a < 1 and F(1, 2) < r < 1
    assert float(r) == 1.0  # This float is an adverse control, never the input r.
    # With only a moment upper bound per outgoing site, four origins may each
    # spend the full budget: the factor 1/4 in face Cauchy is indispensable.
    electric_budget = F(2 ** 14 * 2 ** 8192, 64)
    assert electric_budget == 2 ** 8200
    assert F(1, 4) * 4 * electric_budget == electric_budget
    return {'ell': ell, 'M': m, 'a': str(a), 'one_minus_r': str(s),
            'arc_upper': str(probability), 'L2_error_squared_upper': str(error),
            'binary64_precision_wrongcase_rejected': True}


def matrix_measure_controls() -> dict[str, Any]:
    # Diagonal measures alone are insufficient: at energy 1 this putative
    # mixed measure has a negative quadratic form for coefficients (1,-2).
    bad_energy1 = ((F(1), F(1)), (F(1), F(0)))
    coefficients = (F(1), F(-2))
    bad_quadratic = sum(coefficients[i] * bad_energy1[i][j] * coefficients[j]
                        for i in range(2) for j in range(2))
    assert bad_quadratic == -3
    # A genuine positive MATRIX measure: rank-one weights at energies 0 and 2.
    w0 = ((F(1), F(1)), (F(1), F(1)))
    w2 = ((F(1), F(-1)), (F(-1), F(1)))
    gram = tuple(tuple(w0[i][j] + w2[i][j] for j in range(2)) for i in range(2))
    assert gram == ((2, 0), (0, 2))
    for u, v in ((1, 0), (0, 1), (1, -2), (3, 5)):
        for weight in (w0, w2):
            assert u * u * weight[0][0] + 2 * u * v * weight[0][1] + v * v * weight[1][1] >= 0
    # Equal-time span generated by e0 and (0,1,1) has dimension two in a
    # three-dimensional spectral feature space with L=diag(0,1,2).
    # det[e0,v,Lv]=1: no invariance of that timezero span follows.
    determinant = 1 * (1 * 2 - 1 * 1)
    assert determinant == 1
    return {'incompatible_scalar_diagonal_mixed_quadratic': str(bad_quadratic),
            'positive_matrix_equal_time_gram': [[str(entry) for entry in row] for row in gram],
            'timezero_noninvariance_determinant': determinant,
            'full_GNS_operator_promotion_rejected': True}


def zero_block_order(epsilon: F, n: int) -> dict[str, Any]:
    # L_N=diag(0,1/N,1), v=e1. Q_N v=v, but L_infty e1=0.
    energy = F(1, n)
    finite_filtered_mass = (epsilon / (energy + epsilon)) ** 2
    assert finite_filtered_mass > 0
    limit_of_finite_filtered_mass = F(1)
    after_limit_whole_zero_block_mass = F(0)
    assert limit_of_finite_filtered_mass != after_limit_whole_zero_block_mass
    # Mean removal also leaves e1 when the vacuum is e0.
    mean_removed_limit_mass = F(1)
    assert mean_removed_limit_mass - after_limit_whole_zero_block_mass == 1
    return {'N': n, 'finite_filtered_mass': str(finite_filtered_mass),
            'limit_finite_Q_mass': '1', 'Q_after_limit_mass': '0',
            'mean_removal_wrongcase_extra_mass': str(mean_removed_limit_mass)}


def graph_controls(epsilon: F, cutoff: int) -> dict[str, Any]:
    # Infinite diagonal L_j=j^2 and v_j=1/j: finite norm, divergent first
    # energy moment, and not in D(L). Filtering repairs the SOURCE VECTOR.
    source_norm = sum((F(1, j * j) for j in range(1, cutoff + 1)), F(0))
    unfiltered_first = sum((F(1) for _ in range(cutoff)), F(0))
    unfiltered_graph = sum((F(j * j) for j in range(1, cutoff + 1)), F(0))
    filtered_graph = sum((epsilon ** 2 * j * j / (j * j + epsilon) ** 2
                          for j in range(1, cutoff + 1)), F(0))
    assert unfiltered_first == cutoff and unfiltered_graph >= cutoff
    assert filtered_graph <= epsilon ** 2 * source_norm
    # For every omitted j>cutoff, graph summand <=epsilon^2/j^2;
    # the integral gives the exact outward tail cap epsilon^2/cutoff.
    tail_upper = epsilon ** 2 / cutoff
    assert tail_upper > 0
    return {'cutoff': cutoff, 'unfiltered_first_partial': str(unfiltered_first),
            'filtered_graph_partial': str(filtered_graph),
            'filtered_graph_tail_upper': str(tail_upper),
            'infinite_domain_proof': 'sum epsilon^2/j^2 converges; unfiltered sum 1 diverges'}


def phase_energy_and_momentum() -> dict[str, Any]:
    # Haar theta vacuum of the exact rotor L=256 p^2: periodic U phase is
    # atomless, but sin(theta) vacuum has one energy atom of mass 1/2 at 256.
    harmonic_energy = 256
    harmonic_mass = F(1, 2)
    assert harmonic_energy > 0 and harmonic_mass > 0
    # Four-site alternating unit vectors have coherent Fourier mass V at pi.
    vectors = (1, -1, 1, -1)
    local_average = F(sum(x * x for x in vectors), 4)
    mode_mass = F(sum(x * (-1) ** j for j, x in enumerate(vectors)) ** 2, 4)
    assert local_average == 1 and mode_mass == 4
    assert mode_mass / 4 == local_average
    return {'Haar_phase_nonatom_energy_atom_mass': str(harmonic_mass),
            'energy_atom_location': harmonic_energy,
            'local_average': str(local_average), 'single_nonzero_mode_mass': str(mode_mass),
            'scope': 'Exact rotor and Fourier method controls, not target-law ground data'}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument('--request', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    args = parser.parse_args()
    request = json.loads(args.request.read_text())
    root = Path(__file__).resolve().parent
    assert all(digest(root / name) == pin for name, pin in request['pins'].items())
    epsilon = F(request['epsilon'])
    result = {'kind': 'INDEPENDENT_EXACT_PRINCIPAL_ARC_ADVERSE_METHOD_CONTROLS_NOT_GROUND',
              'arc_constants': [arc_constants(ell) for ell in request['ells']],
              'matrix_feature': matrix_measure_controls(),
              'zero_block_order': [zero_block_order(epsilon, n) for n in request['zero_block_N']],
              'graph': [graph_controls(epsilon, k) for k in request['graph_cutoffs']],
              'phase_energy_momentum': phase_energy_and_momentum(),
              'actual_ground_or_phase_or_pole': False, 'campaign_complete': False}
    assert all(digest(root / name) == pin for name, pin in request['pins'].items())
    with args.output.open('x') as stream:
        json.dump(result, stream, indent=2)
        stream.write('\n')
    print(json.dumps({'matrix_wrongcase': -3, 'zero_block_limit_order_wrongcase': 1,
                      'coherent_nonzero_mode': 4, 'ground_or_pole': False}))


if __name__ == '__main__':
    main()
