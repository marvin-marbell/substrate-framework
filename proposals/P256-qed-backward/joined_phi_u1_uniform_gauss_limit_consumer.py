def basis() -> tuple[list[Any], np.ndarray]:
    x = sp.Matrix([[0, 1], [1, 0]])
    y = sp.Matrix([[0, -sp.I], [sp.I, 0]])
    z = sp.diag(1, -1)
    gamma = [sp.kronecker_product(x, sp.eye(2)), *[sp.kronecker_product(z, p) for p in (x, y, z)]]
    from itertools import combinations
    words = [(i,) for i in range(4)] + list(combinations(range(4), 2)) + list(combinations(range(4), 3)) + [(0, 1, 2, 3)]
    matrices = []
    for word in words:
        m = sp.eye(4)
        for i in word:
            m = m * gamma[i]
        matrices.append((sp.I if len(word) in (2, 3) else 1) * m)
    array = np.asarray([np.asarray(m, dtype=complex) for m in matrices]) / np.sqrt(8)
    return matrices, array


