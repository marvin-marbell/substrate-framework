def divergence(edges: np.ndarray) -> np.ndarray:
    result = edges[..., 0]-np.roll(edges[..., 0], 1, axis=0)
    for axis in (1, 2):
        result += edges[..., axis]
        result -= np.roll(edges[..., axis], 1, axis=axis)
    return result


def transverse_project(edges: np.ndarray) -> np.ndarray:
    """Actual orthogonal Q Q^dagger in local3V coordinates, not a Z^d lattice."""
    N = edges.shape[0]
    frequencies = np.indices((N, N, N))
    eigen = 4*sum(np.sin(np.pi*frequencies[axis]/N)**2 for axis in range(3))
    div_hat = np.fft.fftn(divergence(edges))
    potential_hat = np.zeros_like(div_hat)
    np.divide(div_hat, eigen, out=potential_hat, where=eigen > 1e-14)
    potential = np.fft.ifftn(potential_hat)
    gradient = np.stack([potential-np.roll(potential, -1, axis=axis) for axis in range(3)], axis=-1)
    return edges-gradient


