"""Gauge-adapted selected-configuration correlated states of the L2 QLM torus.

No field-space enumeration: the variational basis is generated by full CAR hops
and independent closed flux strings, then PHP is assembled without modifying H.
Every local matter/link factor has dimensions 4/3; absent global configurations
are a stated variational restriction, not a changed local operator or frozen matter.
"""
from __future__ import annotations
from itertools import combinations
import numpy as np
from scipy import sparse

PREFIX = 'rich_periodic_photon_20261015_'


def geometry():
    positions = np.array([(x, y, z) for x in range(2) for y in range(2) for z in range(2)], dtype=int)
    lookup = {tuple(r): i for i, r in enumerate(positions)}
    edges = []
    for a, r in enumerate(positions):
        for mu in range(3):
            target = r.copy()
            target[mu] = (target[mu] + 1) % 2
            edges.append((a, lookup[tuple(target)], mu))
    incidence = np.zeros((8, 24), dtype=int)
    for e, (a, b, _) in enumerate(edges):
        incidence[a, e] = 1
        incidence[b, e] = -1
    return positions, edges, incidence


POSITIONS, EDGES, INCIDENCE = geometry()
ZERO_FIELD = sum(1 << (16 + 2*e) for e in range(24))


def spin_seeds():
    """All 70 Sz=0 singly occupied determinants, not a fixed Néel product."""
    for up in combinations(range(8), 4):
        occupied = set(up)
        bits = sum(1 << (2*v + (0 if v in occupied else 1)) for v in range(8))
        yield ZERO_FIELD | bits


def neighbors(key):
    """Full -c_b† U_ab c_a plus adjoint, with actual orbital-order CAR parity."""
    bits = key & 65535
    for e, (a, b, _) in enumerate(EDGES):
        shift = 16 + 2*e
        digit = (key >> shift) & 3
        for direction in (1, -1):
            if (direction == 1 and digit == 2) or (direction == -1 and digit == 0):
                continue
            source, target = (a, b) if direction == 1 else (b, a)
            for spin in (0, 1):
                p, q = 2*source + spin, 2*target + spin
                if not ((bits >> p) & 1) or ((bits >> q) & 1):
                    continue
                after = bits ^ (1 << p)
                parity = ((bits & ((1 << p)-1)).bit_count() + (after & ((1 << q)-1)).bit_count()) & 1
                next_bits = after | (1 << q)
                next_key = key + direction*(1 << shift) + next_bits - bits
                yield next_key, (-1 if parity == 0 else 1), e, direction


def loops():
    """Distinct two-link winding strings and four-link positive-axis plaquettes."""
    edge_index = {(a, mu): e for e, (a, _, mu) in enumerate(EDGES)}
    unique = set()
    for a in range(8):
        for mu in range(3):
            e = edge_index[a, mu]
            b = EDGES[e][1]
            winding = [0]*24
            winding[e] = winding[edge_index[b, mu]] = 1
            unique.add(tuple(winding))
            for nu in range(mu+1, 3):
                f = edge_index[a, nu]
                c = EDGES[f][1]
                face = [0]*24
                face[e] += 1
                face[edge_index[b, nu]] += 1
                face[edge_index[c, mu]] -= 1
                face[f] -= 1
                unique.add(tuple(face))
    return sorted(unique)


def basis(kind):
    seeds = set(spin_seeds())
    if kind == 'loop_dressed':
        for flux in loops():
            for sign in (-1, 1):
                offset = sum(sign*f*(1 << (16+2*e)) for e, f in enumerate(flux))
                seeds.update(key+offset for key in spin_seeds())
    expanded = set(seeds)
    for key in seeds:
        expanded.update(target for target, _, _, _ in neighbors(key))
    if kind == 'multi_pair4':
        frontier = expanded-seeds
        for _ in range(3):
            targets = set()
            for key in frontier:
                targets.update(target for target, _, _, _ in neighbors(key))
            frontier = targets-expanded
            expanded.update(frontier)
        expanded.update(basis('loop_dressed'))
    return sorted(expanded)


def assemble(keys):
    index = {key: i for i, key in enumerate(keys)}
    n = len(keys)
    electric = np.empty((n, 24), dtype=np.int8)
    rho = np.empty((n, 8), dtype=np.int8)
    for i, key in enumerate(keys):
        for e in range(24):
            electric[i, e] = ((key >> (16+2*e)) & 3)-1
        for v in range(8):
            rho[i, v] = ((key >> (2*v)) & 1) + ((key >> (2*v+1)) & 1)-1
    diagonal = (electric.astype(float)**2).sum(axis=1)/32 + 2*(rho.astype(float)**2).sum(axis=1)
    rows, cols, values, edge_ids, directions = [], [], [], [], []
    omitted_counts = np.zeros(n, dtype=int)
    for col, key in enumerate(keys):
        for target, value, edge, direction in neighbors(key):
            row = index.get(target)
            if row is None:
                omitted_counts[col] += 1
            else:
                rows.append(row)
                cols.append(col)
                values.append(value)
                edge_ids.append(edge)
                directions.append(direction)
    rows = np.asarray(rows, dtype=np.int32)
    cols = np.asarray(cols, dtype=np.int32)
    values = np.asarray(values, dtype=float)
    hopping = sparse.coo_matrix((values, (rows, cols)), shape=(n, n)).tocsr()
    hamiltonian = hopping + sparse.diags(diagonal, format='csr')
    return dict(keys=keys, electric=electric, rho=rho, diagonal=diagonal, H=hamiltonian,
                hopping=hopping, rows=rows, cols=cols, values=values,
                edge_ids=np.asarray(edge_ids), directions=np.asarray(directions), omitted_counts=omitted_counts)


def source_geometry(q_bits):
    """Link-centred real periodic modes; i factors removed per axis consistently.

For q in {0,pi}, exp(i q.r) is real. Link-centred Fourier phases on pi axes
are i. Rephasing each pi-axis amplitude by -i makes the discrete divergence
row d_mu=2 sin(q_mu/2) real, so transverse directions use its nullspace.
The selected real link coefficient on such axes is (-1)^r; on zero-q axes
it is the same. This convention corresponds to longitudinal phase alignment.
"""
    q_bits = np.asarray(q_bits, dtype=int)
    d = 2*q_bits.astype(float)
    longitudinal = d/np.linalg.norm(d)
    _, _, vh = np.linalg.svd(longitudinal[None, :], full_matrices=True)
    polarizations = np.vstack((vh[1:], longitudinal))
    # The link Fourier source uses a phase i on pi axes. Keep it, rather than
    # dropping phases that would mix the discrete longitudinal constraint.
    site_phase = (-1.0)**(POSITIONS @ q_bits)
    phases = np.array([site_phase[a]*(1j if q_bits[mu] else 1) for a, _, mu in EDGES])
    # In original link-centred convention divergence is imaginary 2sin(q/2).
    # Transforming to site-origin link variables removes i on the pi axes.
    # Real Hermitian quadratures at self-inverse q have divergence weights 2q.
    coefficients = np.array([[site_phase[a]*p[mu]/np.sqrt(8) for a, _, mu in EDGES] for p in polarizations])
    return dict(q=(np.pi*q_bits).tolist(), q_bits=q_bits.tolist(), discrete_gradient=d.tolist(),
                polarizations=polarizations, coefficients=coefficients, density=site_phase/np.sqrt(8),
                formal_link_centered_phases=phases)


def small_physical_case():
    """Matched two-site one-link spinful Gauss sector: actual sparse solve."""
    states = []
    for bits in range(16):
        for flux in (-1, 0, 1):
            n0 = (bits & 1) + ((bits >> 1) & 1)
            n1 = ((bits >> 2) & 1) + ((bits >> 3) & 1)
            if flux+n0-1 == 0 and -flux+n1-1 == 0:
                states.append((bits, flux))
    lookup = {state: i for i, state in enumerate(states)}
    H = np.zeros((len(states), len(states)))
    E = np.diag([e for _, e in states])
    for col, (bits, flux) in enumerate(states):
        H[col, col] = flux*flux/32 + 2*sum((((bits >> (2*v)) & 1)+((bits >> (2*v+1)) & 1)-1)**2 for v in range(2))
        for direction in (-1, 1):
            if abs(flux+direction) > 1:
                continue
            for spin in (0, 1):
                p, q = (spin, 2+spin) if direction == 1 else (2+spin, spin)
                if (bits >> p) & 1 and not ((bits >> q) & 1):
                    after = bits ^ (1 << p)
                    parity = ((bits & ((1 << p)-1)).bit_count()+(after & ((1 << q)-1)).bit_count()) & 1
                    H[lookup[after | (1 << q), flux+direction], col] = -(-1)**parity
    energies, vectors = np.linalg.eigh(H)
    # The physical singlet block has coupling 2 to one doublon combination.
    expected = (4+1/32-np.sqrt((4+1/32)**2+16))/2
    J = 1j*(H@E-E@H)
    return dict(dimension=len(states), energies=energies.tolist(), ground_expected=expected,
                ground_error=abs(float(energies[0])-expected), hermiticity=float(np.max(np.abs(H-H.T))),
                E_current_source_norm=float(np.linalg.norm(J@vectors[:, 0])),
                hopping_off_E_commutator=float(np.linalg.norm(np.diag(np.diag(H))@E-E@np.diag(np.diag(H)))),
                actual_library_operation='numpy.linalg.eigh of full two-site CAR/Gauss Hamiltonian')
