def tensor(left,right):
    return {a|(b<<16):x*y for a,x in left.items() for b,y in right.items()}


def hop(packet,spin,dagger=False):
    terms=[]
    for flavour,colour,s,t in product(range(2),range(3),range(2),range(2)):
        coefficient=spin[s,t]
        if coefficient==0:continue
